"""
第 6 周 · 核心机制 10：RAG 全链路名词级预习
================================================================
【对应知识点】文档第 6 周第四任务：开始 RAG 理论预习（第 7 周要用）

【周次学习要点】
  - 只记"每一环的输入是什么、输出是什么"，不实现解析与切分（那是第 7 周）。
  - 九环节串起来：解析 → 切分 → 嵌入 → 索引 → 检索 → 重排 → 组装 → 生成 → 引用。
  - "检索质量决定答案质量上限"——这是第 7~12 周的主线判断。

【易忽略细节】
  1. 文档第 7 周才要求实装 PDF/Word/HTML 解析与四种切分，本周越界实现就违反边界。
  2. 嵌入与索引是两件事：前者产出向量，后者负责可检索的存储结构。
  3. 引用（citation）是 RAG 与普通 LLM 调用的关键差别，面试常问。

【示例用途】可运行：`python -m week06.core_mechanisms.10_rag_preview`
             第 7 周将逐环节展开实验
"""
from __future__ import annotations

RAG_STAGES: tuple[tuple[str, str, str], ...] = (
    ("解析", "PDF/Word/HTML/Markdown 原始文件", "带结构的纯文本"),
    ("切分", "长文本", "若干语义完整的 chunk"),
    ("嵌入", "chunk 文本", "向量数组"),
    ("索引", "向量 + 元数据", "可检索的向量库"),
    ("检索", "用户问题向量", "Top-K 候选 chunk"),
    ("重排", "Top-K 候选 + 问题", "按相关性重排的少量 chunk"),
    ("组装", "重排结果 + Prompt 模板", "带上下文的 Prompt"),
    ("生成", "Prompt", "答案文本"),
    ("引用", "答案 + chunk 来源", "可溯源答复"),
)


def demo() -> None:
    print("环节 | 输入                         | 输出")
    for name, source, target in RAG_STAGES:
        print(f"{name:<4} | {source:<26} | {target}")
    print("\n本周只预习名词；第 7 周才实装解析与切分实验。")


if __name__ == "__main__":
    demo()
