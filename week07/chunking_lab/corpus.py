"""
第 7 周 · 动手项目语料：一份结构化的中文运维知识库
================================================================
【对应知识点】文档第 7 周切分实验："同一份文档跑四种策略"

【周次学习要点】
  - 语料自带标题层级、编号条款、Markdown 表格与专有名词 SGCC-4012 / ERR_4012。
  - 这些结构正是固定长度切分最容易切断的位置，便于观察策略差异。
  - 文本内嵌在代码里，不需要二进制 fixture，测试可直接复用。

【易忽略细节】
  1. 专有名词必须整块保留，否则 embedding 阶段语义会被稀释（第 8 周体现）。
  2. 表格行一旦被切断，"故障码 → 处置建议"的对应关系就丢了。
  3. 条款编号（第 N 条）是语义边界，比句号更适合作为切分中的回退分隔符。

【示例用途】被 chunking_lab/evaluate.py 与 core_mechanisms 切分样例引用
"""
from __future__ import annotations

import re

from week07.engineering.models import Document

HEADING_RE = re.compile(r"^(#{1,6})\s+(.+?)\s*$")

CORPUS_MARKDOWN = """# SGCC-4012 网关运维知识库
本文档面向 SGCC-4012 网关的现场运维与故障处置，适用于一线值班与二线排障。
文档中所有条款均为教学示例，不代表任何真实生产系统的配置。

## 1 适用范围与术语
第1条 本规范适用于 SGCC-4012 网关的部署、升级、回滚与日常巡检。
第2条 cyclone 表示业务侧告警级别，数值越大影响面越广，处置优先级越高。

### 1.1 术语表
SGCC-4012 是本实验中的网关代号，ERR_4012 是其上游连接超时故障码。
巡检窗口指每日 02:00 至 04:00 的低峰时段，变更应尽量安排在该窗口内。
值班工程师需要在工单中同时记录故障码、告警级别与受影响人数。

## 2 告警分级与响应
第3条 cyclone 级别 1 表示单点告警，不影响整体服务，可在工作时间内处理。
第4条 cyclone 级别 2 表示局部降级，需在 30 分钟内响应并同步值班组长。
第5条 cyclone 级别 3 表示核心链路受损，需立即拉起应急群并通知oncall。
第6条 级别 3 的故障若持续超过 15 分钟，应自动升级为级别 4 并启动回滚。

### 2.1 响应动作
值班人员先确认告警来源，再判断是否属于误报，随后按级别执行对应动作。
对于级别 2 以上的告警，必须在工单中写明影响人数与初步根因。
不要在未确认根因前重启网关，否则会丢失现场日志与链路追踪上下文。

## 3 故障码对照表
| 故障码 | 含义 | 处置建议 |
| --- | --- | --- |
| ERR_4012 | 上游连接超时 | 检查上游健康状态与连接池余量 |
| ERR_4013 | 鉴权令牌过期 | 刷新令牌并复核时钟同步 |
| ERR_4014 | 请求体过大 | 检查网关限流配置与客户端重试策略 |
| ERR_4015 | 下游响应格式异常 | 回查最近一次 schema 变更记录 |

### 3.1 排障顺序
第7条 出现 ERR_4012 时，先查上游健康探测，再查连接池，最后查网络策略。
第8条 出现 ERR_4013 时，优先核对时钟偏差，其次确认令牌签发服务状态。
第9条 同一故障码在十分钟内出现超过 20 次，应合并为一个事件再处置。

## 4 变更与回滚
第10条 所有变更必须先在小流量环境验证，验证通过后方可全量发布。
第11条 回滚脚本必须提前准备，且回滚耗时不得大于变更窗口的一半。
第12条 回滚完成后需要保留至少 24 小时的观察期，期间禁止二次变更。

### 4.1 发布检查清单
检查项包括配置版本、依赖版本、健康检查端点与熔断阈值四项。
任何一项缺失都不得进入发布流程，尤其不要在缺少健康检查时强行灰度。
发布记录应写入知识库，与本文档的条款编号建立可追溯的关联关系。

## 5 复盘与知识沉淀
第13条 级别 3 以上故障必须在 48 小时内产出复盘文档。
第14条 复盘文档应包含时间线、根因、改进项与责任人四部分。
第15条 改进项需要进入迭代计划，未闭环的改进项应在下次复盘中重提。
历史复盘按月归档，检索时以故障码与条款编号作为主要过滤条件。
"""


def corpus_headings(markdown: str = CORPUS_MARKDOWN) -> list[str]:
    """抽取 Markdown 标题文本，作为 Document.sections 的近似值。"""
    titles: list[str] = []
    for line in markdown.splitlines():
        match = HEADING_RE.match(line)
        if match:
            titles.append(match.group(2).strip())
    return titles


def build_corpus_document() -> Document:
    """把内置语料包装成统一 Document，不经过磁盘 IO。"""
    return Document(
        doc_id="sgcc-runbook",
        title="SGCC-4012 网关运维知识库",
        path="corpus.md",
        text=CORPUS_MARKDOWN,
        sections=corpus_headings(),
        page=1,
    )


__all__ = ["CORPUS_MARKDOWN", "build_corpus_document", "corpus_headings"]
